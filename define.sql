
    create table alimentazioni (
        id_alimentazione integer generated by default as identity,
        tipo_alimentazione varchar(255) not null,
        primary key (id_alimentazione)
    );

    create table bici (
        id_bici integer generated by default as identity,
        id_freno integer,
        id_sospensione integer,
        id_veicolo integer,
        n_corone integer not null,
        n_marce integer not null,
        pieghevole boolean,
        primary key (id_bici)
    );

    create table categorie (
        id_categoria integer generated by default as identity,
        tipo_categoria varchar(255) not null,
        primary key (id_categoria)
    );

    create table colori (
        id_colore integer generated by default as identity,
        colore varchar(255) not null,
        primary key (id_colore)
    );

    create table freni (
        id_freno integer generated by default as identity,
        tipo_freno varchar(255) not null,
        primary key (id_freno)
    );

    create table macchine (
        cc integer not null,
        id_macchina integer generated by default as identity,
        id_targa integer,
        id_veicolo integer,
        n_porte integer not null,
        primary key (id_macchina)
    );

    create table marche (
        id_marca integer generated by default as identity,
        nome_marca varchar(255) not null,
        primary key (id_marca)
    );

    create table modelli (
        id_modello integer generated by default as identity,
        nome_modello varchar(255) not null,
        primary key (id_modello)
    );

    create table moto (
        cc integer not null,
        id_moto integer generated by default as identity,
        id_targa integer,
        id_veicolo integer,
        primary key (id_moto)
    );

    create table sospensioni (
        id_sospensione integer generated by default as identity,
        tipo_sospensione varchar(255) not null,
        primary key (id_sospensione)
    );

    create table targhe (
        id_targa integer generated by default as identity,
        codice_targa varchar(255) not null unique,
        primary key (id_targa)
    );

    create table tipo_veicoli (
        id_tipo_veicolo integer generated by default as identity,
        tipo_veicolo varchar(255) not null,
        primary key (id_tipo_veicolo)
    );

    create table veicoli (
        anno_produzione integer not null,
        id_alimentazione integer,
        id_categoria integer,
        id_colore integer,
        id_marca integer,
        id_modello integer,
        id_veicolo integer generated by default as identity,
        n_ruote integer not null,
        primary key (id_veicolo)
    );
