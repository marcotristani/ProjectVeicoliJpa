
    create table alimentazioni (
        id integer generated by default as identity,
        nome_alimentazione varchar(255) not null,
        pattern varchar(255),
        primary key (id)
    );

    create table bici (
        freno_id integer not null,
        id integer generated by default as identity,
        n_corone integer not null,
        n_marce integer not null,
        pieghevole boolean,
        sospensione_id integer not null,
        veicolo_id integer unique,
        primary key (id)
    );

    create table categorie (
        id integer generated by default as identity,
        nome_categoria varchar(255) not null,
        primary key (id)
    );

    create table colori (
        id integer generated by default as identity,
        nome_colore varchar(255) not null,
        primary key (id)
    );

    create table freni (
        id integer generated by default as identity,
        tipo_freno varchar(255) not null,
        primary key (id)
    );

    create table full_veicolo (
        anno_produzione integer,
        cc integer,
        id integer generated by default as identity,
        numero_marce integer,
        numero_porte integer,
        numero_ruote integer,
        pieghevole boolean,
        alim varchar(255),
        categ varchar(255),
        colore varchar(255),
        marca varchar(255),
        modello varchar(255),
        targa varchar(255),
        tipo varchar(255),
        tipo_sospenzione varchar(255),
        primary key (id)
    );

    create table macchine (
        cc integer not null,
        id integer generated by default as identity,
        id_veicolo integer,
        n_porte integer not null,
        veicolo_id integer unique,
        targa varchar(255),
        primary key (id)
    );

    create table marche (
        id integer generated by default as identity,
        nome_marca varchar(255) not null,
        primary key (id)
    );

    create table moto (
        cc integer not null,
        id integer generated by default as identity,
        id_veicolo integer,
        veicolo_id integer unique,
        targa varchar(255),
        primary key (id)
    );

    create table tipo_sospensioni (
        id integer generated by default as identity,
        status boolean not null,
        nome_sospensione varchar(255) not null,
        pattern varchar(255) not null,
        primary key (id)
    );

    create table tipo_veicoli (
        id integer generated by default as identity,
        tipo_veicolo varchar(255) not null,
        primary key (id)
    );

    create table veicoli (
        alimentazione_id integer not null,
        anno_produzione integer not null,
        categoria_id integer not null,
        colore_id integer not null,
        id integer generated by default as identity,
        marca_id integer not null,
        n_ruote integer not null,
        tipo_veicolo_id integer not null,
        data_inserimento timestamp(6) not null,
        modello varchar(255) not null,
        tipo_alimentazione_pattern varchar(255),
        tipo_categoria_pattern varchar(255),
        primary key (id)
    );

